// Generates src/app/shared/icon/icons.ts from the bootstrap-icons package (MIT).
// Only the icons listed here are bundled. Add a name, then run: npm run icons
import { readFileSync, writeFileSync } from 'node:fs';

const NAMES = [
  'grid-1x2', 'briefcase', 'globe2', 'building', 'people', 'shield-lock', 'gear',
  'chevron-down', 'chevron-right', 'chevron-expand', 'layout-sidebar', 'sun', 'moon-stars',
  'circle-half', 'box-arrow-right', 'list', 'x-lg', 'check2', 'search', 'plus-lg',
  'three-dots', 'arrow-left', 'exclamation-triangle', 'inbox', 'shield-x', 'plug',
  'person-circle', 'arrow-repeat',
];

const out = {};
for (const name of NAMES) {
  const svg = readFileSync(new URL(`../node_modules/bootstrap-icons/icons/${name}.svg`, import.meta.url), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  out[name] = inner.replace(/\s+/g, ' ');
}
const body = Object.entries(out).map(([k, v]) => `  '${k}': '${v}',`).join('\n');
writeFileSync(new URL('../src/app/shared/icon/icons.ts', import.meta.url),
  `// Generated by scripts/build-icons.mjs from bootstrap-icons (MIT). Do not edit.\n` +
  `export const ICONS = {\n${body}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`);
console.log(`Wrote ${NAMES.length} icons`);

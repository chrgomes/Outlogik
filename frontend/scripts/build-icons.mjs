// Generates the icon sets in brand/icon/ from the bootstrap-icons package (MIT).
// Each site bundles only its own set. Add a name to the right list, then run: npm run icons
import { readFileSync, writeFileSync } from 'node:fs';

const APP = [
  'grid-1x2', 'briefcase', 'globe2', 'building', 'people', 'shield-lock', 'gear',
  'chevron-down', 'chevron-right', 'chevron-expand', 'layout-sidebar', 'sun', 'moon-stars',
  'circle-half', 'box-arrow-right', 'list', 'x-lg', 'check2', 'search', 'plus-lg',
  'three-dots', 'arrow-left', 'exclamation-triangle', 'inbox', 'shield-x', 'plug',
  'person-circle', 'arrow-repeat', 'graph-up', 'heart-pulse', 'link-45deg', 'check-circle-fill',
  'circle', 'clock-history', 'envelope', 'arrow-right', 'speedometer2', 'file-earmark-bar-graph',
  // website admin
  'window-stack', 'sliders', 'download', 'trash', 'box-arrow-up-right', 'megaphone',
];

const MARKETING = [
  'chevron-down', 'list', 'x-lg', 'arrow-right', 'arrow-up-right', 'check2',
  // product modules
  'briefcase', 'search', 'graph-up', 'megaphone', 'pencil-square', 'bar-chart-line',
  'file-earmark-bar-graph', 'speedometer2',
  // audiences
  'building', 'search-heart', 'person', 'people', 'shop',
  // page content
  'globe2', 'shield-check', 'diagram-3', 'window-stack', 'lightning-charge', 'heart-pulse',
  'link-45deg', 'clock-history', 'envelope', 'arrow-repeat', 'check-circle-fill',
];

const svg = (name) => readFileSync(
  new URL(`../node_modules/bootstrap-icons/icons/${name}.svg`, import.meta.url), 'utf8')
  .replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim().replace(/\s+/g, ' ');

const header = '// Generated by scripts/build-icons.mjs from bootstrap-icons (MIT). Do not edit.\n';
const all = [...new Set([...APP, ...MARKETING])].sort();
writeFileSync(new URL('../brand/icon/icons.ts', import.meta.url), header +
  `export type IconName =\n${all.map((n) => `  | '${n}'`).join('\n')};\n\n` +
  `export type IconSet = Partial<Record<IconName, string>>;\n`);

for (const [file, names, constName] of [['app', APP, 'APP_ICONS'], ['marketing', MARKETING, 'MARKETING_ICONS']]) {
  const body = names.map((n) => `  '${n}': '${svg(n)}',`).join('\n');
  writeFileSync(new URL(`../brand/icon/icons-${file}.ts`, import.meta.url), header +
    `import { IconSet } from './icons';\n\nexport const ${constName}: IconSet = {\n${body}\n};\n`);
}
console.log(`Wrote ${APP.length} app icons and ${MARKETING.length} marketing icons`);
